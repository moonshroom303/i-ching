  // Line labels in Wilhelm's wording.
  const ORD_DE = ['', 'zweitem', 'drittem', 'viertem', 'fünftem', ''];
  const ORD_EN = ['', 'second', 'third', 'fourth', 'fifth', ''];
  function lineLabel(lang, index, yang) {
    if (lang === 'de') {
      const w = yang ? 'Neun' : 'Sechs';
      if (index === 0) return `Anfangs eine ${w}`;
      if (index === 5) return `Oben eine ${w}`;
      return `${w} auf ${ORD_DE[index]} Platz`;
    }
    const w = yang ? 'Nine' : 'Six';
    if (index === 0) return `${w} at the beginning`;
    if (index === 5) return `${w} at the top`;
    return `${w} in the ${ORD_EN[index]} place`;
  }
  function allLabel(lang, n) {
    if (lang === 'de') return n === 1 ? 'Lauter Neunen' : 'Lauter Sechsen';
    return n === 1 ? 'All nines' : 'All sixes';
  }

